# Commented out IPython magic to ensure Python compatibility.

# Step 1: Mount Google Drive
from google.colab import drive
drive.mount('/content/drive')

# Install OpenAI Whisper if it is not already installed
# %pip install -U openai-whisper

# Step 2: Import libraries
import os
import json
import time
import csv
import whisper
from google.colab import files

# Step 3: Create the output folder
output_folder = "/content/drive/MyDrive/transcripts"
os.makedirs(output_folder, exist_ok=True)

# CSV report path
csv_path = os.path.join(
    output_folder,
    "transcription_report.csv"
)

# Step 4: Load the Whisper model only once
start_loading = time.time()

model = whisper.load_model("large-v2")

loading_time = time.time() - start_loading

print(f"Model loading time: {loading_time:.2f} seconds")
print(f"Model loading time: {loading_time / 60:.2f} minutes")


# Step 5: Keep asking for files until the user chooses No
while True:

    print("\n====================================")
    print("       WHISPER TRANSCRIPTION")
    print("====================================")
    print("Upload an audio/video file using the file picker.")

    uploaded = files.upload()

    # Check whether a file was uploaded
    if not uploaded:
        print("No file uploaded. Please try again.")
        continue

    # Get the uploaded filename
    filename = next(iter(uploaded))

    # Get the temporary local path in Colab
    audio_path = os.path.abspath(filename)

    # Step 6: Clean the filename
    # Example:
    # 2.make_tasty_biryani_masala_in_2_minutes_easily(128k).m4a
    # File number: 2
    # Title: make_tasty_biryani_masala_in_2_minutes_easily

    name = os.path.splitext(filename)[0]

    parts = name.split(".", 1)

    if len(parts) == 2 and parts[0].strip().isdigit():
        file_number = parts[0].strip()
        title = parts[1].split("(")[0].strip()
    else:
        file_number = ""
        title = name.split("(")[0].strip()

    # Create a clean filename for the JSON output
    if file_number:
        output_name = f"{file_number}.{title}"
    else:
        output_name = title

    json_path = os.path.join(
        output_folder,
        output_name + ".json"
    )

    # Avoid overwriting an existing transcript
    if os.path.exists(json_path):
        print("\nThis transcript already exists:")
        print(json_path)
        print("Rename the file or skip it to avoid overwriting.")
        continue

    # Step 7: Transcribe the uploaded file
    print(f"\nOriginal filename: {filename}")
    print(f"File number: {file_number}")
    print(f"Clean title: {title}")
    print("\nTranscription started...")

    start_time = time.time()

    try:
        result = model.transcribe(
            audio_path,
            language="hi",
            task="translate",
            word_timestamps=False
        )

        processing_time = time.time() - start_time

    except Exception as e:
        print("\nTranscription failed:", e)
        continue

    # Step 8: Create timestamped chunks
    chunks = []

    for segment in result["segments"]:
        chunks.append({
            "number": file_number,
            "title": title,
            "start": segment["start"],
            "end": segment["end"],
            "text": segment["text"].strip()
        })

    # Step 9: Prepare JSON data
    transcript_data = {
        "number": file_number,
        "title": title,
        "source_file": filename,
        "chunks": chunks,
        "text": result["text"].strip()
    }

    # Step 10: Save JSON to Google Drive
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(
            transcript_data,
            f,
            indent=4,
            ensure_ascii=False
        )

    print("\nTranscription completed successfully!")
    print("JSON saved at:", json_path)
    print(f"Processing time: {processing_time:.2f} seconds")
    print(f"Processing time: {processing_time / 60:.2f} minutes")

    # Step 11: Append the processing time to CSV
    file_exists = (
        os.path.exists(csv_path)
        and os.path.getsize(csv_path) > 0
    )

    with open(
        csv_path,
        "a",
        newline="",
        encoding="utf-8-sig"
    ) as f:

        writer = csv.writer(f)

        # Write headings only for a new or empty CSV
        if not file_exists:
            writer.writerow([
                "FileNumber",
                "Filename",
                "Time (seconds)",
                "Time (minutes)"
            ])

        writer.writerow([
            file_number,
            filename,
            round(processing_time, 2),
            round(processing_time / 60, 2)
        ])

    print("CSV report updated.")

    # Step 12: Ask whether to transcribe another file
    choice = input(
        "\nDo you want to transcribe another file? (yes/no): "
    ).strip().lower()

    if choice not in ("yes", "y"):
        print("\nProgram finished.")
        print("Transcripts folder:", output_folder)
        print("CSV report:", csv_path)
        break

